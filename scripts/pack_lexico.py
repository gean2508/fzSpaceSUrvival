def genero(nucleo: str) -> str:
    """`"m"` o `"f"` para la primera palabra del núcleo — la que manda la
    concordancia (`"tacho de basura negro"`, no `"negra"`)."""
    cabeza = nucleo.split()[0] if nucleo.split() else nucleo
    if cabeza in MASCULINO_EXPLICITO:
        return "m"
    if cabeza in FEMENINO_EXPLICITO:
        return "f"
    if cabeza.endswith(("a", "as", "ción", "sión", "dad", "tad", "umbre")):
        return "f"
    return "m"
