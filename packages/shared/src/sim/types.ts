/** Top-down world: X horizontal, Z depth. Y (up) used for parkour/verticality. */
export interface Vec2 {
  x: number;
  z: number;
}

export type EntityKind = "player" | "npc" | "projectile";

/** Ability slots map to bits in InputState.abilities. */
export const ABILITY_SLOTS = 4;

/**
 * Deterministic movement state machine. Shared by server + client so animation
 * and physics agree everywhere.
 *  - idle/running/sprinting: ground locomotion
 *  - wall_trek: pressing into a climbable wall (pre-climb)
 *  - climbing: ascending a wall face (drains stamina, moves on Y)
 *  - hanging: holding the top edge of a wall (press action to mantle up)
 *  - exhausted: stamina depleted; forced to the ground, reduced control
 */
export type MovementState =
  | "idle"
  | "running"
  | "sprinting"
  | "wall_trek"
  | "climbing"
  | "hanging"
  | "exhausted";

export const MOVEMENT_STATES: MovementState[] = [
  "idle",
  "running",
  "sprinting",
  "wall_trek",
  "climbing",
  "hanging",
  "exhausted",
];

/**
 * One player's intent for a tick. The server NEVER trusts positions, only this.
 * `seq` lets the client reconcile its prediction against the server.
 */
export interface InputState {
  seq: number;
  moveX: number; // -1..1
  moveZ: number; // -1..1
  aimX: number; // unit aim direction (combat/abilities/look)
  aimZ: number;
  abilities: number; // bitmask, bit i = ability slot i pressed this tick
  sprint: number; // 0 | 1 — sprint modifier
  action: number; // 0 | 1 — parkour/interact action (climb, mantle, gather)
}

export function emptyInput(seq = 0): InputState {
  return {
    seq,
    moveX: 0,
    moveZ: 0,
    aimX: 0,
    aimZ: 1,
    abilities: 0,
    sprint: 0,
    action: 0,
  };
}

/** Serializable per-entity state. Mirrors the Colyseus schema fields. */
export interface EntitySnapshot {
  id: string;
  kind: EntityKind;
  classId: string;
  x: number;
  y: number; // vertical (parkour); 0 on the ground
  z: number;
  vx: number;
  vz: number;
  rot: number; // facing angle (radians)
  hp: number;
  maxHp: number;
  dead: boolean;
  team: number;
  ownerId: string; // projectiles/summons: source entity id ("" otherwise)
  state: MovementState; // movement FSM state (players)
  stamina: number;
  maxStamina: number;
  hunger: number; // 0..100 (100 = full)
  thirst: number; // 0..100 (100 = hydrated)
}

/** Static climbable/blocking box in the world (AABB footprint + height). */
export interface Obstacle {
  id: string;
  x: number; // center
  z: number;
  halfW: number; // half-extent on X
  halfD: number; // half-extent on Z
  height: number; // climbable top surface height
}

export type InteractableKind = "tree" | "rock" | "container";

/** A gatherable/lootable node generated by code. */
export interface InteractableSnapshot {
  id: string;
  kind: InteractableKind;
  x: number;
  z: number;
  radius: number; // interaction range
  looted: boolean;
}

/** Inventory primitive — base for the survival crafting loop (later phases). */
export interface InventoryItem {
  itemId: string;
  qty: number;
}

export type MatchStatus = "lobby" | "playing" | "ended";

/** Full world state for one tick. Produced by both server and offline sim. */
export interface WorldSnapshot {
  tick: number;
  timeMs: number;
  status: MatchStatus;
  wave: number;
  entities: EntitySnapshot[];
  /** Static world geometry (sent so remote clients can render + predict). */
  obstacles: Obstacle[];
  interactables: InteractableSnapshot[];
  /** Last input seq the sim processed per player id (for reconciliation). */
  lastProcessedInput: Record<string, number>;
}
